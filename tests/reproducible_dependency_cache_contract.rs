use std::path::Path;

const LOCK: &str = include_str!("../Cargo.lock");
const CARGO_TOML: &str = include_str!("../Cargo.toml");
const TOOLCHAIN: &str = include_str!("../rust-toolchain.toml");
const VENDOR_CONFIG: &str = include_str!("../.cargo/vendor-config.toml");
const VENDOR_SH: &str = include_str!("../scripts/vendor-dependencies.sh");
const VENDOR_CMD: &str = include_str!("../scripts/vendor-dependencies.cmd");
const VERIFY_SH: &str = include_str!("../scripts/verify-vendored-dependencies.sh");
const VERIFY_CMD: &str = include_str!("../scripts/verify-vendored-dependencies.cmd");
const UPDATE_SH: &str = include_str!("../scripts/update.sh");
const UPDATE_CMD: &str = include_str!("../UPDATE_TOOLBOX.cmd");
const CI: &str = include_str!("../.github/workflows/ci.yml");
const GITIGNORE: &str = include_str!("../.gitignore");
const ROADMAP: &str = include_str!("../docs/ROADMAP.md");
const ARCHITECTURE: &str = include_str!("../docs/ARCHITECTURE.md");
const DOC: &str = include_str!("../docs/REPRODUCIBLE_DEPENDENCY_CACHE.md");

#[test]
fn committed_lockfile_is_cargo_generated_and_matches_application_version() {
    let lock = LOCK.replace("\r\n", "\n");
    assert!(lock.starts_with("# This file is automatically @generated by Cargo."));
    assert!(lock.contains("\nversion = 4\n"));
    assert!(lock.contains("[[package]]\nname = \"dangomushi\""));
    assert!(lock.contains("version = \"0.5.28\""));
    assert!(CARGO_TOML.contains("version = \"0.5.28\""));
    assert!(lock.len() > 50_000);
}

#[test]
fn rebuild_toolchain_is_exact_not_a_moving_channel() {
    assert!(TOOLCHAIN.contains("channel = \"1.99.1\""));
    assert!(TOOLCHAIN.contains("profile = \"minimal\""));
    assert!(!TOOLCHAIN.contains("channel = \"stable\""));
    assert!(CI.contains("dtolnay/rust-toolchain@1.99.1"));
    assert!(!CI.contains("dtolnay/rust-toolchain@stable"));
}

#[test]
fn vendor_source_replacement_is_explicit_and_offline() {
    for required in [
        "[source.crates-io]",
        "replace-with = \"vendored-sources\"",
        "[source.vendored-sources]",
        "directory = \"vendor\"",
        "[net]",
        "offline = true",
    ] {
        assert!(VENDOR_CONFIG.contains(required), "missing vendor config: {required}");
    }

    assert!(!Path::new(".cargo/config.toml").exists());
    assert!(GITIGNORE.lines().any(|line| line == "vendor/"));
    assert!(GITIGNORE.lines().any(|line| line == "vendor.pending/"));
}

#[test]
fn vendor_generation_is_locked_versioned_and_non_overwriting() {
    for script in [VENDOR_SH, VENDOR_CMD] {
        assert!(script.contains("Cargo.lock"));
        assert!(script.contains("cargo vendor --locked --versioned-dirs vendor.pending"));
        assert!(script.contains("vendor.pending"));
        assert!(script.contains("metadata --frozen --format-version 1"));
    }

    assert!(VENDOR_SH.contains("[ -e vendor ]"));
    assert!(VENDOR_CMD.contains("if exist \"vendor\""));
}

#[test]
fn frozen_verification_covers_core_and_desktop_without_registry_fallback() {
    for script in [VERIFY_SH, VERIFY_CMD] {
        assert!(script.contains("--config"));
        assert!(script.contains("vendor-config.toml"));
        assert!(script.contains("metadata --frozen"));
        assert!(script.contains("test --frozen"));
        assert!(script.contains("build --frozen --release --bin dangomushi"));
        assert!(script.contains("test --frozen --features desktop --lib"));
        assert!(script.contains(
            "build --frozen --release --features desktop --bin dangomushi-desktop"
        ));
    }
}

#[test]
fn routine_update_and_ci_paths_refuse_lockfile_rewrites() {
    for required in [
        "cargo test --locked",
        "cargo build --locked --release --bin dangomushi",
        "cargo build --locked --release --features desktop --bin dangomushi-desktop",
    ] {
        assert!(UPDATE_SH.contains(required), "Unix update missing: {required}");
        assert!(UPDATE_CMD.contains(required), "Windows update missing: {required}");
    }

    for required in [
        "cargo test --locked",
        "cargo build --locked --release --bin dangomushi",
        "cargo test --locked --features desktop --lib",
        "cargo build --locked --release --features desktop --bin dangomushi-desktop",
        "offline-vendor:",
        "sh scripts/vendor-dependencies.sh",
        "sh scripts/verify-vendored-dependencies.sh",
    ] {
        assert!(CI.contains(required), "CI missing: {required}");
    }

    assert!(!UPDATE_SH.contains("cargo update"));
    assert!(!UPDATE_CMD.contains("cargo update"));
}

#[test]
fn docs_keep_cache_scope_narrow_and_advance_exactly_once() {
    for required in [
        "Cargo.lock",
        "cargo vendor --locked --versioned-dirs",
        "Rust 1.99.1",
        "not claim a fully hermetic",
        "vendor/ is deliberately ignored by Git",
        "does not silently change existing backup scope",
    ] {
        assert!(
            DOC.contains(required) || ARCHITECTURE.contains(required),
            "missing dependency-cache boundary: {required}"
        );
    }

    assert!(ROADMAP.contains("- [x] **Reproducible dependency cache/vendor strategy**"));
    assert!(ROADMAP.contains("- [x] **Recovery snapshots**"));
    assert!(ROADMAP.contains("- [x] **Restore verification**"));
    assert!(ROADMAP.contains(
        "- [ ] **Portable release bundles per operating system** — Exactly One Next Task"
    ));
}
